/*
 *	tad_pat.c
 *	The patterns a figure's shapes are drawn with, by number
 *
 *	A shape names what its line and its inside are drawn with by a
 *	number: l_pat and f_pat. 0 is nothing at all; 1 to 127 are the fixed
 *	patterns every record may use without saying what they are; from
 *	128 on they are the record's own, given in its <patterns> section.
 *	Most of the fixed ones are a plain colour. The rest are a sixteen by
 *	sixteen mask drawn in black: a row of it is a word, the leftmost
 *	pixel in the top bit.
 */

