/*
 *	emu_rom.h
 *	Small ROMs for the tests of BeFC and BeSFC, written here so that no game
 *	or ROM of unknown licence is needed: each sounds a steady tone, and
 *	shows a colour on the screen that button A changes, for ever.
 *	rom has room for EMU_ROM_MAX bytes, all set to 0xEA first. Answers the
 *	length of the ROM.
 */

#ifndef EMU_ROM_H
#define EMU_ROM_H

#define EMU_ROM_MAX	0x8010

/*
 * A NROM of 16 KB: pulse 1 sounding 440 Hz; at each blank, palette 0 a colour
 * by button A of the first pad, 0x16 up, 0x2a down, the background shown.
 */
static inline int emu_rom_nes( unsigned char *rom )
{
	static const unsigned char	prg[] = {
		0xa9, 0x01, 0x8d, 0x15, 0x40,		/* $C000 the pulse channel on */
		0xa9, 0xbf, 0x8d, 0x00, 0x40,		/* its loudest, a constant volume */
		0xa9, 0xfd, 0x8d, 0x02, 0x40,		/* its period */
		0xa9, 0x00, 0x8d, 0x03, 0x40,
		0xa9, 0x08, 0x8d, 0x01, 0x20,		/* the background shown */
		0x2c, 0x02, 0x20, 0x10, 0xfb,		/* $C019 wait for a blank */
		0xa9, 0x01, 0x8d, 0x16, 0x40,		/* the pad latched */
		0xa9, 0x00, 0x8d, 0x16, 0x40,
		0xad, 0x16, 0x40, 0x29, 0x01,		/* the first bit it gives is A */
		0xf0, 0x04,
		0xa9, 0x2a, 0xd0, 0x02,
		0xa9, 0x16,
		0xaa,
		0xa9, 0x3f, 0x8d, 0x06, 0x20,		/* palette 0 */
		0xa9, 0x00, 0x8d, 0x06, 0x20,
		0x8e, 0x07, 0x20,
		0xa9, 0x00, 0x8d, 0x06, 0x20, 0x8d, 0x06, 0x20,
		0x4c, 0x19, 0xc0,
		0x40					/* $C04E the vectors that are not the start */
	};
	static const unsigned char	head[8] = { 'N', 'E', 'S', 0x1a, 1, 0, 0, 0 };
	int	i;

	for ( i = 0; i < 8; i++ ) rom[i] = head[i];
	for ( i = 0; i < (int)sizeof(prg); i++ ) rom[16 + i] = prg[i];
	rom[16 + 0x3ffa] = 0x4e;
	rom[16 + 0x3ffb] = 0xc0;
	rom[16 + 0x3ffc] = 0x00;
	rom[16 + 0x3ffd] = 0xc0;
	rom[16 + 0x3ffe] = 0x4e;
	rom[16 + 0x3fff] = 0xc0;
	return 16 + 0x4000;
}

/*
 * A LoROM of 32 KB: the sound processor given a program of its own that
 * sounds voice 0 on a square wave, then at each blank colour 0 by button A
 * of the first pad, red up, green down.
 */
#define EMU_SFC_SPC_AT		0xa0		/* where in the ROM the sound program is */
static inline int emu_rom_sfc( unsigned char *rom )
{
	static const unsigned char	prg[] = {
		0x78, 0x18, 0xfb, 0xe2, 0x30,			/* $8000 native, 8 bits */
		0xa9, 0x0f, 0x8d, 0x00, 0x21,			/* the screen on */
		0xa9, 0x01, 0x8d, 0x00, 0x42,			/* the pads read at each blank */
		0xa9, 0xaa, 0xcd, 0x40, 0x21, 0xd0, 0xfb,	/* the sound processor's loader says it is there */
		0xa9, 0x00, 0x8d, 0x42, 0x21,			/* to $0200 */
		0xa9, 0x02, 0x8d, 0x43, 0x21,
		0xa9, 0x01, 0x8d, 0x41, 0x21,
		0xa9, 0xcc, 0x8d, 0x40, 0x21,
		0xcd, 0x40, 0x21, 0xd0, 0xfb,
		0xa2, 0x00,					/* each byte, and the loader's echo of its count */
		0xbd, EMU_SFC_SPC_AT, 0x80,
		0x8d, 0x41, 0x21,
		0x8a,
		0x8d, 0x40, 0x21,
		0xcd, 0x40, 0x21, 0xd0, 0xfb,
		0xe8,
		0xe0, 99,
		0xd0, 0xec,
		0xa9, 0x0d, 0x8d, 0x42, 0x21,			/* run from $020D */
		0xa9, 0x02, 0x8d, 0x43, 0x21,
		0x9c, 0x41, 0x21,
		0x8a, 0x1a, 0x1a,
		0x8d, 0x40, 0x21,
		0xad, 0x12, 0x42, 0x10, 0xfb,			/* $8058 wait for a blank */
		0xad, 0x12, 0x42, 0x29, 0x01, 0xd0, 0xf9,	/* and for the pads read */
		0x9c, 0x21, 0x21,
		0xad, 0x18, 0x42, 0x30, 0x0a,			/* its top bit is A */
		0xa9, 0x1f, 0x8d, 0x22, 0x21, 0x9c, 0x22, 0x21,
		0x80, 0x0a,
		0xa9, 0xe0, 0x8d, 0x22, 0x21, 0xa9, 0x03, 0x8d, 0x22, 0x21,
		0xad, 0x12, 0x42, 0x30, 0xfb,			/* the blank over */
		0x80, 0xd1
	};
	/* for the sound processor, at $0200: the sample's directory, one sample, the program */
	static const unsigned char	spc[99] = {
		0x04, 0x02, 0x04, 0x02,
		0xc3, 0x77, 0x77, 0x77, 0x77, 0x99, 0x99, 0x99, 0x99,	/* a block that loops: a square */
		0x8f, 0x6c, 0xf2, 0x8f, 0x20, 0xf3,	/* sound not muted, no echo written */
		0x8f, 0x0c, 0xf2, 0x8f, 0x7f, 0xf3,	/* the main volume */
		0x8f, 0x1c, 0xf2, 0x8f, 0x7f, 0xf3,
		0x8f, 0x2c, 0xf2, 0x8f, 0x00, 0xf3,	/* no echo */
		0x8f, 0x3c, 0xf2, 0x8f, 0x00, 0xf3,
		0x8f, 0x5d, 0xf2, 0x8f, 0x02, 0xf3,	/* the directory */
		0x8f, 0x00, 0xf2, 0x8f, 0x7f, 0xf3,	/* voice 0: its volume */
		0x8f, 0x01, 0xf2, 0x8f, 0x7f, 0xf3,
		0x8f, 0x02, 0xf2, 0x8f, 0x00, 0xf3,	/* its pitch: 16 samples at 8 kHz, a 500 Hz wave */
		0x8f, 0x03, 0xf2, 0x8f, 0x04, 0xf3,
		0x8f, 0x04, 0xf2, 0x8f, 0x00, 0xf3,	/* its sample */
		0x8f, 0x05, 0xf2, 0x8f, 0x00, 0xf3,	/* a fixed level */
		0x8f, 0x07, 0xf2, 0x8f, 0x7f, 0xf3,
		0x8f, 0x4c, 0xf2, 0x8f, 0x01, 0xf3,	/* key on */
		0x2f, 0xfe
	};
	static const char	name[] = "TESSRON SELFTEST     ";
	int	i;

	for ( i = 0; i < (int)sizeof(prg); i++ ) rom[i] = prg[i];
	for ( i = 0; i < (int)sizeof(spc); i++ ) rom[EMU_SFC_SPC_AT + i] = spc[i];
	for ( i = 0; i < 21; i++ ) rom[0x7fc0 + i] = (unsigned char)name[i];
	rom[0x7fd5] = 0x20;
	rom[0x7fd7] = 0x08;
	rom[0x7fdc] = 0xff;
	rom[0x7fdd] = 0xff;
	rom[0x7fde] = 0x00;
	rom[0x7fdf] = 0x00;
	rom[0x7ffc] = 0x00;
	rom[0x7ffd] = 0x80;
	return 0x8000;
}

/*
 * The same program in a ROM of the shape of a real cartridge: size bytes, mapped as
 * the map byte says (bit 0: HiROM), of the given cartridge type, a title that is not
 * ASCII as on the Japanese games, and 512 bytes of a copier before it when copier.
 * rom has room for size + 512 bytes. Answers the length of the file.
 */
static inline long emu_rom_sfc_shape( unsigned char *rom, long size, int copier, int type, int map )
{
	unsigned char	*b = rom + ( copier ? 512 : 0 );
	long		h = ( map & 1 ) ? 0xffc0 : 0x7fc0, i;
	int		order = 0;

	for ( i = 0; i < size + ( copier ? 512 : 0 ); i++ ) rom[i] = 0xea;
	emu_rom_sfc(b);
	if ( map & 1 ) {
		for ( i = 0x7fff; i >= 0; i-- ) {
			b[0x8000 + i] = b[i];
			b[i] = 0xea;
		}
	}
	for ( i = 0; i < 21; i++ ) b[h + i] = 0xc0 + (unsigned char)i;
	while ( ( 1024L << order ) < size ) order++;
	b[h + 0x15] = (unsigned char)map;
	b[h + 0x16] = (unsigned char)type;
	b[h + 0x17] = (unsigned char)order;
	b[h + 0x18] = ( type == 2 ) ? 3 : 0;
	return size + ( copier ? 512 : 0 );
}

#endif /* EMU_ROM_H */
