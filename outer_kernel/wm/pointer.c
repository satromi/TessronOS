/*
 *	pointer.c
 *	The pointer on the screen (design 16.4, 16.5)
 *
 *	Sixteen shapes, twenty-four pixels square: hands -- white, with a
 *	black outline -- and beside most of them a black mark with a white
 *	edge that says which way the action goes. Each shape is two planes.
 *	The mask says which pixels are laid at all; the body says which of
 *	those are black, the rest being white. A row of a plane is four
 *	bytes, the leftmost pixel in the top bit of the first.
 *
 *	The picture over each shape has '#' where the pixel is black and
 *	'+' where it is white.
 *
 *	The pointer is laid down last, after the windows, at every screen.
 *	Nothing is saved from under it: the screen is built afresh from
 *	the ground up each time, so what was under the pointer is drawn
 *	again anyway.
 */

